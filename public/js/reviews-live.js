/*
 * Live guest-review figures.
 *
 * The figures rendered into the HTML by scripts/update-reviews.py are read by
 * hand off each platform's listing. This script refreshes the ones it can,
 * in the browser, from the owner's own Repuso feed -- the same subscription
 * behind the review badge on theoaks.uk, so our number and his dashboard agree
 * instead of drifting apart.
 *
 * Only Oxford has a Repuso widget. Dorset has none, so its figures stay
 * hand-maintained and the combined total is live-Oxford plus manual-Dorset.
 *
 * Three things this deliberately does NOT do:
 *
 *   1. No AggregateRating markup. Repuso's own widget injects one claiming the
 *      total as the site's rating; Google's structured-data policy does not
 *      allow marking up ratings gathered from other platforms, so we take the
 *      number and leave the schema behind.
 *   2. No error state. The endpoint is undocumented and may change or vanish.
 *      Every failure path leaves the server-rendered figures exactly as they
 *      are -- which are real, just a little behind. Nobody sees a broken page,
 *      and anyone without JavaScript sees the fallback, not a gap.
 *   3. No layout change. It rewrites text inside markup the generator owns,
 *      so the page looks identical whether or not the fetch lands.
 *
 * Repuso groups by platform, merging its two Tripadvisor channels and its two
 * Airbnb channels. Our fallback breakdown lists each Airbnb listing separately.
 * Both add up correctly within themselves, so the live breakdown is rendered
 * per platform to match the live total rather than mixing the two shapes.
 */
(function () {
  "use strict";

  /* ch:data -- generated by scripts/update-reviews.py; do not edit by hand */
  var DATA = {
    "badge": "VisitEngland Gold",
    "checked": "2026-09-16",
    "properties": {
      "oxford": {
        "name": "Cedar Hollow Oxford, The Oaks",
        "short": "Cedar Hollow Oxford",
        "page": "oxford-reviews.html",
        "rating": 5.0,
        "count": 269,
        "sources": [
          {
            "platform": "Google",
            "listing": "",
            "url": "https://www.google.com/travel/hotels/entity/CgsInOXTpI3TstrTARAB"
          },
          {
            "platform": "Tripadvisor",
            "listing": "",
            "url": "https://www.tripadvisor.co.uk/Hotel_Review-g186361-d32973964-Reviews-Cedar_Hollow_Oxford_The_Oaks-Oxford_Oxfordshire_England.html"
          },
          {
            "platform": "Airbnb",
            "listing": "Whimsical Treehouse in C. S. Lewis' footsteps",
            "url": "https://www.airbnb.co.uk/rooms/722435848290391530"
          },
          {
            "platform": "Airbnb",
            "listing": "Narnia Inspired Mr Tumnus Cave",
            "url": "https://www.airbnb.co.uk/rooms/1280483083604154655"
          }
        ],
        "live": {
          "endpoint": "https://api.thereviewsplace.com/v1/widgets/posts/34454"
        }
      },
      "dorset": {
        "name": "Mallinson's Woodland Retreat",
        "short": "Cedar Hollow Dorset",
        "page": "dorset-reviews.html",
        "rating": 4.9,
        "count": 208,
        "sources": [
          {
            "platform": "Google",
            "listing": "",
            "url": "https://share.google/l7CQQex4bleR7Txlq"
          },
          {
            "platform": "Tripadvisor",
            "listing": "",
            "url": "https://www.tripadvisor.co.uk/Hotel_Review-g4041688-d5063870-Reviews-Mallinson_s_Woodland_Retreat-Holditch_Dorset_England.html"
          }
        ]
      }
    }
  };
  /* /ch:data */

  var CACHE_KEY = "ch-reviews:";
  var CACHE_MS = 30 * 60 * 1000;
  var TIMEOUT_MS = 6000;

  if (!window.fetch || !document.createTreeWalker || !DATA.properties) return;

  /* ---------------------------------------------------------------------
     Marker plumbing

     The generator wraps every figure in comment markers, which survive into
     the DOM, so the nodes can be found without adding hooks to the markup.
     --------------------------------------------------------------------- */

  function comments(re) {
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_COMMENT, null, false);
    var hits = [];
    var node;
    while ((node = walker.nextNode())) {
      var m = node.nodeValue.trim().match(re);
      if (m) hits.push({ node: node, match: m });
    }
    return hits;
  }

  /* Everything between an opening marker and its closing one; they are
     siblings, so walking nextSibling is enough. */
  function between(start, closing) {
    var nodes = [];
    var n = start.nextSibling;
    while (n && !(n.nodeType === 8 && n.nodeValue.trim() === closing)) {
      nodes.push(n);
      n = n.nextSibling;
    }
    return { nodes: nodes, end: n };
  }

  function find(nodes, sel) {
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i];
      if (n.nodeType !== 1) continue;
      if (n.matches && n.matches(sel)) return n;
      var hit = n.querySelector && n.querySelector(sel);
      if (hit) return hit;
    }
    return null;
  }

  function findAll(nodes, sel) {
    var out = [];
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i];
      if (n.nodeType !== 1) continue;
      if (n.matches && n.matches(sel)) out.push(n);
      if (n.querySelectorAll) {
        Array.prototype.push.apply(out, n.querySelectorAll(sel));
      }
    }
    return out;
  }

  /* ---------------------------------------------------------------------
     Figures
     --------------------------------------------------------------------- */

  function weighted(parts) {
    var total = 0;
    var sum = 0;
    parts.forEach(function (p) {
      total += p.count;
      sum += p.rating * p.count;
    });
    if (!total) return { rating: 0, count: 0 };
    /* Repuso reports one channel at 5.03, above its own scale, so clamp. */
    return { rating: Math.min(5, Math.round((sum / total) * 10) / 10), count: total };
  }

  function num(n) {
    return n.toLocaleString ? n.toLocaleString("en-GB") : String(n);
  }

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  /* ---------------------------------------------------------------------
     Rendering
     --------------------------------------------------------------------- */

  function updateStrip(nodes, fig, badge) {
    var numeral = find(nodes, ".stars-rating span");
    if (numeral) numeral.textContent = fig.rating.toFixed(1) + " ";

    var line = find(nodes, "p.text-size-medium");
    if (line) line.textContent = "from " + num(fig.count) + " guest reviews • " + badge;

    var link = find(nodes, "a.ch-reviews-link");
    if (link) {
      link.setAttribute(
        "aria-label",
        "Read guest reviews: rated " + fig.rating.toFixed(1) + " from " +
          num(fig.count) + " guest reviews, " + badge
      );
    }

    /* The fifth star is filled by a two-stop gradient; both stops sit at the
       same offset, so moving them moves the boundary. */
    var pct = Math.max(0, Math.min(1, fig.rating - 4)) * 100;
    findAll(nodes, "linearGradient stop").forEach(function (stop) {
      stop.setAttribute("offset", pct + "%");
    });
  }

  function listingsFor(prop, platform) {
    return (prop.sources || []).filter(function (s) {
      return s.platform.toLowerCase() === String(platform).toLowerCase();
    });
  }

  /* One row per platform, matching how Repuso groups them, so the rows add up
     to the headline. Where a platform has several listings behind it, they are
     named after the figure rather than hidden. */
  function breakdownHTML(prop, fig, platforms) {
    var rows = platforms.map(function (p) {
      var links = listingsFor(prop, p.label);
      var rating = p.rating % 1 === 0 ? p.rating.toFixed(1) : String(p.rating);
      var label;
      if (links.length === 1) {
        label = '<a href="' + esc(links[0].url) + '" target="_blank" rel="noopener">' +
          esc(p.label) + "</a>";
      } else if (links.length > 1) {
        label = esc(p.label) + " <span class=\"ch-reviews__listings\">(" +
          links.map(function (l) {
            return '<a href="' + esc(l.url) + '" target="_blank" rel="noopener">' +
              esc(l.listing || l.platform) + "</a>";
          }).join(", ") + ")</span>";
      } else {
        label = esc(p.label);
      }
      return "  <li>" + label + " &mdash; " + rating + " from " + num(p.count) + " reviews</li>";
    });

    return '<p class="text-size-large"><strong>' + esc(prop.name) + "</strong> &mdash; " +
      fig.rating.toFixed(1) + " from " + num(fig.count) + " guest reviews</p>\n" +
      '<ul class="ch-list text-size-large">\n' + rows.join("\n") + "\n</ul>\n" +
      '<p class="text-size-medium">Each figure comes from that platform&#x27;s own ' +
      "listing and refreshes automatically, so the total here is the one the " +
      "platforms are showing right now.</p>";
  }

  function replaceBetween(start, end, html) {
    var n = start.nextSibling;
    while (n && n !== end) {
      var next = n.nextSibling;
      n.parentNode.removeChild(n);
      n = next;
    }
    var tpl = document.createElement("div");
    tpl.innerHTML = "\n" + html + "\n";
    while (tpl.firstChild) start.parentNode.insertBefore(tpl.firstChild, end);
  }

  /* ---------------------------------------------------------------------
     Apply
     --------------------------------------------------------------------- */

  /* "A, B and C" -- each platform once, in data order. */
  function sourcesSentence(prop) {
    var seen = [];
    (prop.sources || []).forEach(function (s) {
      if (seen.indexOf(s.platform) === -1) seen.push(s.platform);
    });
    if (seen.length < 2) return esc(seen[0] || "");
    return esc(seen.slice(0, -1).join(", ")) + " and " + esc(seen[seen.length - 1]);
  }

  function apply(key, fig, platforms, items) {
    var prop = DATA.properties[key];
    var badge = DATA.badge || "";

    renderWall(key, items);

    /* The combined figure: this property live, every other one as published.
       Computed whether or not a combined strip is on this page, because the
       running prose quotes it too. */
    var parts = [{ rating: fig.rating, count: fig.count }];
    Object.keys(DATA.properties).forEach(function (other) {
      if (other === key) return;
      parts.push({
        rating: DATA.properties[other].rating,
        count: DATA.properties[other].count
      });
    });
    var allFig = weighted(parts);

    comments(/^ch:reviews\s+([\w-]+)$/).forEach(function (hit) {
      var name = hit.match[1];
      var figure = name === key ? fig : (name === "all" ? allFig : null);
      if (!figure) return;
      updateStrip(between(hit.node, "/ch:reviews").nodes, figure, badge);
    });

    markTotals(key, fig);
    markTotals("all", allFig);

    /* The per-platform breakdown on this property's own reviews page. */
    comments(/^ch:reviews-breakdown\s*([\w-]*)$/).forEach(function (hit) {
      if (hit.match[1] !== key) return;
      var span = between(hit.node, "/ch:reviews-breakdown");
      if (!span.end) return;
      replaceBetween(hit.node, span.end, breakdownHTML(prop, fig, platforms));
    });

    /* The hub listing: one line per woodland. Rebuilt from the data rather
       than patched, so there is no half-replaced sentence to go wrong. */
    comments(/^ch:reviews-index$/).forEach(function (hit) {
      var span = between(hit.node, "/ch:reviews-index");
      var item = find(span.nodes, 'a[href="' + prop.page + '"]');
      if (!item || !item.parentNode) return;
      item.parentNode.innerHTML =
        '<a href="' + esc(prop.page) + '">' + esc(prop.short) + "</a> &mdash; " +
        fig.rating.toFixed(1) + " from " + num(fig.count) +
        " guest reviews on " + sourcesSentence(prop);
    });
  }

  /* ---------------------------------------------------------------------
     The review wall

     The same response carries the reviews themselves. Unlike the figures,
     these have no server-rendered fallback -- there is nothing sensible to
     show in place of "the latest reviews" -- so the section ships hidden and
     is revealed only once there is something real to put in it.
     --------------------------------------------------------------------- */

  var PLATFORMS = {
    googleplace: "Google",
    google: "Google",
    tripadvisor: "Tripadvisor",
    airbnb: "Airbnb",
    facebook: "Facebook",
    booking: "Booking.com"
  };

  var VISIBLE = 6;

  function platformName(type) {
    return PLATFORMS[String(type || "").toLowerCase()] || "";
  }

  /* The only markup the feed carries is <br />. Strip every tag, escape what
     is left, then put the line breaks back -- so nothing a reviewer typed can
     become markup on our page. */
  function reviewHTML(raw) {
    var text = String(raw || "")
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<[^>]*>/g, "")
      .replace(/[ \t]+\n/g, "\n")
      .trim();
    return esc(text).replace(/\n+/g, "<br>");
  }

  function monthYear(stamp) {
    var m = String(stamp || "").match(/^(\d{4})-(\d{2})/);
    if (!m) return "";
    var months = ["January", "February", "March", "April", "May", "June", "July",
      "August", "September", "October", "November", "December"];
    return months[Number(m[2]) - 1] + " " + m[1];
  }

  function initial(name) {
    var c = String(name || "").trim().charAt(0);
    return c ? c.toUpperCase() : "•";
  }

  function usable(items) {
    var seen = {};
    return (items || []).filter(function (i) {
      if (!i || i.disabled || i.status !== 1) return false;
      if (!String(i.text || "").trim()) return false;
      if (!platformName(i.type)) return false;
      if (seen[i.id]) return false;
      seen[i.id] = 1;
      return true;
    }).sort(function (a, b) {
      return String(b.posted_on || "").localeCompare(String(a.posted_on || ""));
    });
  }

  function card(item, hidden) {
    var platform = platformName(item.type);
    var name = String(item.from_name || "").trim() || "A guest";
    var when = monthYear(item.posted_on);
    var rating = Math.max(1, Math.min(5, Math.round(Number(item.rating_value) || 5)));
    var meta = when ? platform + " &middot; " + esc(when) : platform;

    var li = document.createElement("li");
    li.className = "ch-wall__card";
    if (hidden) li.hidden = true;

    var source = "";
    if (item.post_url && /^https:\/\//i.test(item.post_url)) {
      source = '<a class="ch-wall__src" href="' + esc(item.post_url) +
        '" target="_blank" rel="noopener nofollow">Read it on ' + platform + "</a>";
    }

    li.innerHTML =
      '<div class="ch-wall__head">' +
        '<span class="ch-wall__avatar" aria-hidden="true">' + esc(initial(name)) + "</span>" +
        '<div class="ch-wall__who">' +
          '<p class="ch-wall__name">' + esc(name) + "</p>" +
          '<p class="ch-wall__meta">' + meta + "</p>" +
        "</div>" +
      "</div>" +
      '<p class="ch-wall__stars" role="img" aria-label="Rated ' + rating +
        ' out of 5">' + new Array(rating + 1).join("★") + "</p>" +
      '<div class="ch-wall__text">' + reviewHTML(item.text) + "</div>" +
      source;
    return li;
  }

  function renderWall(key, items) {
    var hosts = document.querySelectorAll('[data-ch-wall="' + key + '"]');
    if (!hosts.length) return;
    var usableItems = usable(items);
    if (!usableItems.length) return;

    Array.prototype.forEach.call(hosts, function (host) {
      var grid = host.querySelector(".ch-wall__grid");
      var button = host.querySelector(".ch-wall__more");
      if (!grid) return;

      grid.innerHTML = "";
      usableItems.forEach(function (item, i) {
        grid.appendChild(card(item, i >= VISIBLE));
      });

      if (button) {
        var hiddenCount = Math.max(0, usableItems.length - VISIBLE);
        if (!hiddenCount) {
          button.hidden = true;
        } else {
          button.hidden = false;
          button.textContent = "Show " + hiddenCount + " more";
          button.addEventListener("click", function () {
            Array.prototype.forEach.call(grid.children, function (li) {
              li.hidden = false;
            });
            button.hidden = true;
            /* Send the keyboard somewhere sensible now the button is gone. */
            var revealed = grid.children[VISIBLE];
            if (revealed) {
              revealed.setAttribute("tabindex", "-1");
              revealed.focus();
            }
          });
        }
      }

      host.hidden = false;
    });
  }

  /* Totals quoted in running prose, wrapped by the generator. */
  function markTotals(name, fig) {
    var sel = '[data-ch-total="' + name + '"]';
    Array.prototype.forEach.call(document.querySelectorAll(sel), function (el) {
      el.textContent = num(fig.count);
    });
  }

  /* ---------------------------------------------------------------------
     Fetch
     --------------------------------------------------------------------- */

  function cached(key) {
    try {
      var raw = window.sessionStorage.getItem(CACHE_KEY + key);
      if (!raw) return null;
      var parsed = JSON.parse(raw);
      if (Date.now() - parsed.at > CACHE_MS) return null;
      return parsed;
    } catch (e) {
      return null;
    }
  }

  /* Only the fields actually rendered are kept: the raw response is ~80KB of
     widget presentation, far more than belongs in session storage. */
  function cache(key, badge, items) {
    try {
      window.sessionStorage.setItem(
        CACHE_KEY + key,
        JSON.stringify({ at: Date.now(), badge: badge, items: items })
      );
    } catch (e) {}
  }

  function slim(items) {
    return (items || []).slice(0, 60).map(function (i) {
      return {
        id: i.id,
        type: i.type,
        status: i.status,
        disabled: i.disabled,
        text: i.text,
        from_name: i.from_name,
        posted_on: i.posted_on,
        rating_value: i.rating_value,
        post_url: i.post_url
      };
    });
  }

  /* Repuso's payload carries a `badge` array, one entry per platform. Anything
     else in the response is the widget's own presentation and is ignored. */
  function platformsFrom(badge) {
    if (!badge || !badge.length) return null;
    var out = [];
    for (var i = 0; i < badge.length; i++) {
      var b = badge[i];
      var count = Number(b.count != null ? b.count : b.official_num_reviews);
      var rating = Number(b.official_score != null ? b.official_score : b.rating_average);
      if (!isFinite(count) || count <= 0 || !isFinite(rating) || rating <= 0) return null;
      out.push({ label: String(b.label || ""), count: count, rating: Math.min(5, rating) });
    }
    return out;
  }

  function load(key) {
    var prop = DATA.properties[key];
    if (!prop || !prop.live || !prop.live.endpoint) return;

    var hit = cached(key);
    if (hit) {
      var fromCache = platformsFrom(hit.badge);
      if (fromCache) {
        apply(key, weighted(fromCache), fromCache, hit.items);
        return;
      }
    }

    var controller = window.AbortController ? new AbortController() : null;
    var timer = window.setTimeout(function () {
      if (controller) controller.abort();
    }, TIMEOUT_MS);

    var opts = { credentials: "omit", mode: "cors" };
    if (controller) opts.signal = controller.signal;

    window.fetch(prop.live.endpoint, opts)
      .then(function (r) {
        if (!r.ok) throw new Error("status " + r.status);
        return r.json();
      })
      .then(function (json) {
        window.clearTimeout(timer);
        var items = slim(json && json.items);
        var platforms = platformsFrom(json && json.badge);
        /* The reviews can still be shown when the badge is missing or has
           changed shape; they are independent halves of the same response. */
        if (!platforms) {
          if (items.length) renderWall(key, items);
          return;
        }
        var fig = weighted(platforms);
        /* A total that collapses is far more likely to be a changed payload
           than a real drop, so treat it as a failure and keep the fallback. */
        if (fig.count < prop.count * 0.75) {
          if (items.length) renderWall(key, items);
          return;
        }
        cache(key, json.badge, items);
        apply(key, fig, platforms, items);
      })
      .catch(function () {
        window.clearTimeout(timer);
      });
  }

  function start() {
    Object.keys(DATA.properties).forEach(function (key) {
      if (DATA.properties[key].live) load(key);
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", start);
  } else {
    start();
  }
})();
